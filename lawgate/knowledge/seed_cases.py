def generate_cases(n_per_cause: int = 150, seed: int = 42) -> list[dict]:
    """生成确定性的合成案号库。返回 case_registry 行。"""
    rng = random.Random(seed)
    rows: list[dict] = []
    used: set[str] = set()
    seq_counter: dict[tuple, int] = {}

    for cause in CAUSE_ACTIONS:
        made = 0
        guard = 0
        while made < n_per_cause and guard < n_per_cause * 50:
            guard += 1
            code, cname, region = rng.choice(COURTS)
            ctype, ctype_name = rng.choice(CASE_TYPES)
            year = rng.choice([2019, 2020, 2021, 2022, 2023, 2024, 2025])
            key = (year, code, ctype)
            seq_counter[key] = seq_counter.get(key, rng.randint(100, 3000)) + rng.randint(1, 37)
            seq = seq_counter[key]
            case_no = f"（{year}）{code}{ctype}{seq}号"
            if case_no in used:
                continue
            used.add(case_no)
            month = rng.randint(1, 12)
            day = rng.randint(1, 28)
            jy = year + (1 if ctype in ("民终", "民再") and month > 6 else 0)
            rows.append({
                "case_no": case_no,
                "year": year,
                "court_code": code,
                "court_name": cname,
                "case_type": ctype_name,
                "seq_no": seq,
                "cause_action": cause,
                "judgment_date": f"{jy}-{month:02d}-{day:02d}",
                "exists_in_db": 1,
                "region": region,
                "facts": rng.choice(FACT_TEMPLATES[cause]),
                "reasoning": JUDGMENT_REASONING[cause],
            })
            made += 1
    return rows


def render_full_text(row: dict, rng: random.Random) -> str:
    """渲染一份极简合成"判决书"（含案号、案由、法院、说理），供通道 C 语料。"""
    amount = rng.choice(["30000", "50000", "100000", "200000", "450000"])
    facts = row["facts"].format(amount=amount, r=row.get("_rate", 1),
                                year=row["year"] - 2)
    return (
        f"{row['court_name']}\n民事判决书\n{row['case_no']}\n\n"
        f"案由：{row['cause_action']}\n\n"
        f"【原告诉称】{facts}\n\n"
        f"【本院查明】经审理查明，当事人的陈述与提交的证据能够相互印证，"
        f"本院对案件基本事实予以确认。\n\n"
        f"【本院认为】{row['reasoning']}\n\n"
        f"综上，依照相关法律规定，判决如下：\n一、被告于本判决生效之日起十日内"
        f"履行相应义务；\n二、驳回原告的其他诉讼请求。\n\n"
        f"审判长　合成审判员\n审判员　合成审判员\n"
        f"审判员　合成审判员\n{row['judgment_date']}\n"
        f"书记员　合成书记员\n\n"
        f"【合成数据提示】本文书由 CA-LegalGate 项目程序化生成，"
        f"用于离线环境下的系统联调，_不对应任何真实案件_。"
    )
